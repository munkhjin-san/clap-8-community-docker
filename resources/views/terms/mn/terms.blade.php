<h1 style="font-size: 24px;">Үйлчилгээний нөхцөл</h1>
<br>
<div style="line-height:2;">
Glowd (цаашид "Үйлчилгээ" гэх) нь Glowd Inc.-ээс (цаашид "манай компани" гэх) үүлэнд суурилсан бизнесийн чат үйлчилгээ юм.
<br>
Энэхүү гэрээ нь энэхүү үйлчилгээг ашиглах нөхцөлийг тодорхойлсон бөгөөд энэ үйлчилгээний бүх хэрэглэгчдэд (цаашид "хэрэглэгч" гэх) хамаарна.
<br>
Хэрэглэгч эдгээр нөхцлийг зөвшөөрснөөр үйлчилгээг ашиглах боломжтой болно. Компани нь хэрэглэгчийн зөвшөөрлийг авалгүйгээр эдгээр нөхцөлийг өөрчилж болно.
<br>
Хэрэглэгч оруулсан өөрчлөлтийн агуулгыг баталгаажуулсан эсэхээс үл хамааран хэрэглэгч тухайн өөрчлөлтийн дараа энэхүү үйлчилгээг ашигласан тохиолдолд хэрэглэгч энэхүү гэрээг өөрчлөхийг зөвшөөрсөнд тооцно.
<br>
Энэхүү гэрээ нь энэ үйлчилгээний бүх хэрэглэгчдэд хамаарна.
<br>
<br>
1 Акаунт бүртгэл
<br>
<div style="margin-left:30px;line-height:2;">
(1) Энэ үйлчилгээг ашиглахын тулд хэрэглэгч бүртгүүлэх ёстой.
<br>
(2) Та бүртгэлээ бүртгүүлэхдээ мэйл хаяг, гар утасны дугаар эсвэл сошиал хаягаа ашиглаж болно.
<br>
(3) Хэрэглэгчид өөрсдийн эрсдэлээр акаунт бүртгүүлэх бөгөөд бүртгүүлсэн мэдээллийнхээ үнэн зөв, бодитой байдлыг хариуцна.
<br>
(4) Хэрэглэгч үйлчилгээнд бүртгэлээ бүртгүүлж дууссаны дараа Компани нь эдгээр нөхцөлийг зөвшөөрсөнд тооцогдох бөгөөд үйлчилгээг ашиглаж эхэлсэн өдөр нь акаунт бүртгэл дууссан өдөр байна.
<br>
(5) Ашиглаж эхлэх огноог Японы цагаар үндэслэнэ.
<br>
</div>
<br>
2 Нууц үгийн хяналт
<br>
    <div style="margin-left: 30px;line-height:2;">
    (1) Тус үйлчилгээг ашиглахын тулд та өөрийн акаунтад нууц үг тохируулах шаардлагатай.
    <br>
    (2) Та өөрийн бүртгэлтэй холбоотой нууц үгээ хариуцах үүрэгтэй. Нууц үгээ гуравдагч этгээдэд алдахгүйн тулд нууц үгээ зөв хадгалж, ашиглахгүй, бусдад мэдэгдэхгүй байхыг анхаарна уу.
    <br>
    (3) Үйлчилгээнд нэвтрэх үед оруулсан нууц үгийг хэрэглэгч өөрөө оруулсан гэж тооцно. Нэвтрэх үед нууц үгээ оруулснаар хэрэглэгч өөрөө үйлчилгээг ашиглаж байна гэж үзнэ.
    <br>
    (4) Хэрэв та нууц үгээ мартсан бол үйлчилгээнд заасан журмын дагуу нууц үгээ шинэчлэх боломжтой. Гэсэн хэдий ч, хэрэглэгчийн хувийн мэдээллийг баталгаажуулах боломжгүй эсвэл үйлчилгээ ашиглалтын нөхцлийг зөрчсөн гэж үзвэл бид таны нууц үгийг шинэчлэх боломжгүй байх тохиолдол гарч болзошгүй.
    <br>
    (5) Хэрэглэгчид нууц үгээ тогтмол солихыг зөвлөж байна.
    <br>
    </div>
