    4 Үйлчилгээний тасалдал
    Компани нь дараах тохиолдолд үйлчилгээ үзүүлэхээ түр зогсоож болно.
<br>
<div style="margin-left: 30px;line-height:2;">
(a) Системийн засвар үйлчилгээ эсвэл шинэчлэлтийн үед.
<br>
(b) Гал түймэр, эрчим хүчний доголдол, байгалийн гамшиг гэх мэт давагдашгүй хүчин зүйлийн улмаас үйлчилгээ үзүүлэхэд хүндрэлтэй үед.
<br>
(c) Аюулгүй байдлын эрсдэл, гадны халдлага гэх мэт.
<br>
(d) Бусад шаардлагатай тохиолдолд.
<br>
