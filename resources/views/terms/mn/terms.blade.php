11 Оюуны өмчийн эрх
Үйлчилгээтэй холбоотой зохиогчийн эрх, барааны тэмдгийн эрх, патентын эрх болон бусад оюуны өмчийн эрх нь Компани эсвэл Компанид лиценз олгосон гуравдагч этгээдэд хамаарна. Хэрэглэгч бидний урьдчилан зөвшөөрөлгүйгээр эдгээр эрхийг зөрчсөн аливаа үйлдэл хийхийг хориглоно.
