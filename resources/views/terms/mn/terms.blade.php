<br>
(2) Өөрчлөгдсөн нөхцөлийг компаниас зохих журмын дагуу хэрэглэгчдэд мэдэгдэх бөгөөд энэ үеэс эхлэн хүчин төгөлдөр болно.
<br>
(3) Хэрэв хэрэглэгч энэ гэрээг өөрчлөхийг зөвшөөрөхгүй бол хэрэглэгч энэ үйлчилгээг ашиглахаа зогсоож болно. Гэсэн хэдий ч, хэрэв хэрэглэгч энэ үйлчилгээг өөрчилсөн нөхцөлийн дагуу ашиглах юм бол хэрэглэгч өөрчлөгдсөн нөхцөлийг зөвшөөрсөнд тооцогдоно.
