<br>
(1) Компани нь хэрэглэгчдэд интернет орчноор дамжуулан үйлчилгээ үзүүлдэг бөгөөд хэрэглэгч өөрийн хариуцлага, зардлаар уг үйлчилгээг ашиглахад шаардлагатай орчныг(цаашид ""ашиглах орчин"" гэх) бэлтгэнэ.
    <br>
    (2) Ашиглах орчинд дараахь зүйлс орно.
    <div style="margin-left: 30px;line-height:2;">
    (a) Техник хангамж
    <br>
    (b) Програм хангамж
    <br>
    (c) Интернет холболт
    <br>
    (d) Үйл ажиллагааны орчны аюулгүй байдлыг хангах
    <br>
    (e) Үйлчилгээг ашиглахад шаардлагатай бусад орчин
    <br>
    </div>
