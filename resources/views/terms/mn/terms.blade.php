9 Бүртгэл устгах
<br>
Хэрэглэгчид хүссэн үедээ бүртгэлээ устгах боломжтой. Хэрэв та бүртгэлээ устгавал бүртгэлийн мэдээлэл, ашиглалтын түүх зэрэг бүх мэдээлэл устах болно.
<br>
Гэсэн хэдий ч, хэрэв хэрэглэгч эдгээр нөхцлийг зөрчсөн эсвэл Компани үүнийг зохисгүй гэж үзвэл хэрэглэгчийн бүртгэлийг устгаж болно.
