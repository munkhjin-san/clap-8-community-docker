5 Хориглох зүйлс 
<br>
Хэрэглэгчид энэ үйлчилгээг ашиглахдаа дараах үйлдлийг хийхийг хориглоно.
<br>
<div style="margin-left:30px;line-height:2;">
(a) Хууль тогтоомж, нийтийн хэв журам, ёс суртахууныг зөрчсөн үйлдэл
    <br>
    (b) Бусдын хувийн болон нууц мэдээллийг зөвшөөрөлгүйгээр цуглуулах
    <br>
    (c) Энэ үйлчилгээний үйл ажиллагаанд саад учруулсан үйлдлүүд
    <br>
    (d) Үйлчилгээг ашиглахтай холбогдуулан зохисгүй гэж үзсэн бусад үйлдлүүд.
    <br>
</div>
