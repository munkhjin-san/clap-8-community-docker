6 Үнэ
<br>
Одоогийн байдлаар энэ үйлчилгээг ашиглах нь үнэ төлбөргүй. Гэсэн хэдий ч бид ямар ч үед хураамж нэвтрүүлэх эрхтэй бөгөөд хураамж тогтоосон тохиолдолд танд урьдчилан мэдэгдэх болно.
<br>
<br>
7 Татгалзах
<br>
<div style="margin-left:30px;line-height:2;">
(1) Энэ үйлчилгээг ашигласнаар хэрэглэгчдэд учирсан хохирлыг бид хариуцахгүй.
<br>
(2) Үйлчилгээг ашигласнаар хэрэглэгч гуравдагч этгээдэд учруулсан хохирлыг компани хариуцахгүй.
<br>
(3) Хэрэв компани нь зайлшгүй шалтгаанаар үйлчилгээгээ түр зогсоосон эсвэл цуцалсан бол компани нь үүнээс үүдэн учирсан хохирол, хохирол болон бусад зардлыг нөхөн төлөх, нөхөн төлөхөөс чөлөөлөгдөнө.
<br>
</div>
