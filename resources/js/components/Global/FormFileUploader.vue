import FileIcon from '../Board/Mixed/FileIcon.vue'
export default{
    props: ['initialValue'],
    emits: ['updated'],
    data(){
        return{
            entered: false,
            uploadingProgress: 0,
            uploadFiles: this.initialValue ? this.initialValue : []
        }
    },
    components:{FileIcon},
    watch:{
        uploadFiles(after){
            this.$emit('updated', after)
        }
    },
    methods:{
        removeAttachment(file){
            axios.post('post_delete_file', {list: [file.id]})
            .then(response =>{                                       
                const index = this.uploadFiles.findIndex(item => item.id === file.id);
                if (index !== -1) {
                    this.uploadFiles.splice(index, 1);
                }
                this.$emit('updated', this.uploadFiles)
            })
        },
        dropFile(){
            this.entered = false
        },
        fileSelected(){
            if(event.target.files && event.target.files.length){
                
                this.uploadStart(event.target.files)
            }
        },
        triggerUploader(){
            this.$refs.formUploader.click();
        },
        setEnter(val){
            this.entered = val
            console.log('enter', this.entered)
        },
        dropFile(){  
            if(event.dataTransfer.files && event.dataTransfer.files.length){
                
                this.uploadStart(event.dataTransfer.files)
            }
            this.entered = false

        },
        uploadStart(files){
            if(files && files.length){
                const formData = new FormData()                    
                for(var i in files) {                
                    if(files[i].type !== undefined){                         
                        formData.append(i, files[i])
                    }               
                } 
                this.uploadStart(formData)
            
                axios.post('post_file_upload', formData , { onUploadProgress: (e) => this.uploadingProgress = Math.floor((e.loaded * 100) / e.total) } )
                .then(response =>{                                       
                    const files = response.data
                    for(let file of files){
                        this.uploadFiles.push(file)
                    }
                    this.$emit('updated', this.uploadFiles)
                    
                })
                .catch((error) => {
                })
                .then(() => {
                    this.$emit('updated', this.uploadFiles)
                    setTimeout(() => {
                        this.uploadingProgress = 0
                    }, 300);
                    this.$refs.formUploader.value = ''

                });

            }
        },
        
    }
}
