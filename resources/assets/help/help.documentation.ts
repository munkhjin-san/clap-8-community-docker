export const findHelpDocument = (id: string | undefined | null): HelpDocument | undefined =>
    helpDocuments.find((doc) => doc.id === id)

/** An article paired with the topic it belongs to (topic === article for leaf topics). */
export interface HelpDocFlatArticle {
    topic: HelpDocTopic
    article: HelpDocArticle
}

/** Reading-order article list — drives the sidebar links and the prev/next pager. */
export const flattenHelpArticles = (doc: HelpDocument): HelpDocFlatArticle[] =>
    doc.topics.flatMap((topic) =>
        topic.children?.length
            ? topic.children.map((article) => ({ topic, article }))
            : [{ topic, article: topic }],
    )
