/** Help documentation hub data (orthodox docs: left topic nav, right article content). */

/** A renderable content block inside an article body. */
export type HelpBlock =
    | { type: 'h'; text: string }
    | { type: 'p'; text: string }
    | { type: 'ul'; items: string[] }
    | { type: 'note'; text: string }
    | { type: 'img'; src: string; alt?: string }

export interface HelpDocArticle {
    /** Stable slug used in the URL (/help/documentation/{doc}/{article}). */
    id: string
    title: string
    /** Content blocks; omit while the article is unwritten (renders a 準備中 placeholder). */
    body?: HelpBlock[]
}

export interface HelpDocTopic {
    /** Slug; for a topic without children this doubles as its article id. */
    id: string
    title: string
    /** Topic-as-article content (topics without children). */
    body?: HelpBlock[]
    children?: HelpDocArticle[]
}

/** Top-level document (product / feature area) shown on the documentation selector. */
export interface HelpDocument {
    id: string
    title: string
    description: string
    topics: HelpDocTopic[]
}

